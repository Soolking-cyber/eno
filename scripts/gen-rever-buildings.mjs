/**
 * Generate `src/generated/rever-buildings.ts` from the crawl artefacts.
 *
 *   node scripts/gen-rever-buildings.mjs <buildings.jsonl> <projects.json> <listings.json>
 *
 * ⛔ WHY A GENERATED MODULE AND NOT A `Building` TABLE. Name, hero and centroid belong to the
 * BUILDING, not to each of its 157 units — a reviewer's point, and storing them per-row would be
 * both duplicated and unmaintainable. But there are only ~30 buildings from one partner, they change
 * about never, and a table means a second model, a relation and another migration against a database
 * where `prisma db push` emits DROP TABLE for everything it does not manage. A generated module is
 * the pattern this repo already uses for exactly this shape of data (`src/generated/ui-strings.ts`,
 * `vi-overrides.ts`): reviewable in the diff, zero runtime cost, no migration.
 * ⚠️ IF THIS EVER COVERS A SECOND SOURCE, OR GROWS PAST A FEW HUNDRED, MOVE IT TO A TABLE. The
 * counts already come from the database; only the labels live here.
 *
 * ⚠️ The module is keyed by Rever's PROJECT SLUG, which is what `Listing.buildingKey` stores — not
 * by coordinate. See the schema comment on `buildingKey` for why.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const [, , BUILDINGS, PROJECTS, LISTINGS] = process.argv
if (!BUILDINGS || !PROJECTS || !LISTINGS) {
  console.error('usage: gen-rever-buildings.mjs <buildings.jsonl> <projects.json> <listings.json>')
  process.exit(1)
}

const bySlugUrls = new Map()
for (const line of readFileSync(BUILDINGS, 'utf8').split('\n')) {
  if (!line.trim()) continue
  const r = JSON.parse(line)
  if (r.code === 200 && r.slug) {
    if (!bySlugUrls.has(r.slug)) bySlugUrls.set(r.slug, { name: r.name || r.slug, urls: [] })
    bySlugUrls.get(r.slug).urls.push(r.url)
  }
}
const projects = JSON.parse(readFileSync(PROJECTS, 'utf8'))
const listings = new Map(JSON.parse(readFileSync(LISTINGS, 'utf8')).map((r) => [r.url, r]))

/** Only hero urls the optimizer allowlist admits — anything else renders as a 400, not a fallback. */
const ALLOWED = ['https://photo.rever.vn/v3/get/', 'https://photo.rever.vn/photo/v3/',
                 'https://photo.rever.vn/v2/get/', 'https://photo.rever.vn/photo/v2/']

const out = []
for (const [slug, { name, urls }] of [...bySlugUrls].sort((a, b) => b[1].urls.length - a[1].urls.length)) {
  const pts = urls.map((u) => listings.get(u)).filter((r) => r && typeof r.latitude === 'number')
  if (!pts.length) continue
  // Every unit in a project carries the same geocode, so the mean IS that point; averaging simply
  // survives the case where Rever moves one of them without splitting the building in two.
  const lat = pts.reduce((a, r) => a + r.latitude, 0) / pts.length
  const lng = pts.reduce((a, r) => a + r.longitude, 0) / pts.length
  const rawHero = projects[slug]?.hero ?? null
  const hero = rawHero && ALLOWED.some((p) => rawHero.startsWith(p)) ? rawHero : null
  const district = pts[0]?.district ?? null
  out.push({ slug, name, hero, lat: +lat.toFixed(6), lng: +lng.toFixed(6), district, units: urls.length })
}

const dropped = out.filter((b) => !b.hero).map((b) => b.slug)
const body = `/**
 * GENERATED by scripts/gen-rever-buildings.mjs — do not edit by hand.
 *
 * The ~${out.length} Rever.vn projects the imported rentals belong to. \`Listing.buildingKey\` holds the
 * slug; this module holds the label, hero image and centroid that belong to the BUILDING rather
 * than to each of its units. Unit COUNTS are never stored here — they come from the database
 * against the live feed filters, or a tower would advertise a stale number.
 *
 * ⚠️ \`hero\` is the project's own og:image from \`rever.vn/du-an/<slug>\`. These are the developer's
 * marketing renders, not photographs, and several carry the developer's own branding. They are on
 * \`photo.rever.vn\`, which \`next.config.ts\` already allowlists — a hero on any other host is
 * dropped at generation time, because the optimizer would 400 it rather than fall back.
 */
export type ReverBuilding = {
  slug: string
  name: string
  hero: string | null
  lat: number
  lng: number
  district: string | null
}

export const REVER_BUILDINGS: Record<string, ReverBuilding> = {
${out.map((b) => `  ${JSON.stringify(b.slug)}: { slug: ${JSON.stringify(b.slug)}, name: ${JSON.stringify(b.name)}, hero: ${JSON.stringify(b.hero)}, lat: ${b.lat}, lng: ${b.lng}, district: ${JSON.stringify(b.district)} },`).join('\n')}
}

/** Stable list, biggest first at generation time. */
export const REVER_BUILDING_SLUGS = Object.keys(REVER_BUILDINGS)
`
writeFileSync('src/generated/rever-buildings.ts', body)
console.log(`  wrote src/generated/rever-buildings.ts — ${out.length} buildings`)
console.log(`  heroes: ${out.length - dropped.length}/${out.length}${dropped.length ? `  (dropped, wrong host: ${dropped.join(', ')})` : ''}`)
console.log(`  units covered: ${out.reduce((a, b) => a + b.units, 0)}`)
