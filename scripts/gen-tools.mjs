#!/usr/bin/env node
/**
 * Regenerates src/lib/tools/content.generated.ts from src/content/tools/*.json, as scripts/gen-guides.mjs does for the guides: a
 * JSON file read with `fs` at run time would not reach the standalone build, so each is imported. No directory or no file is an
 * empty index (eno.vn ships with no generated tool). tools.test.ts fails while the index is out of step with the directory.
 * Usage: node scripts/gen-tools.mjs
 */
import { existsSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(fileURLToPath(import.meta.url), '..', '..')
const DIR = join(ROOT, 'src/content/tools')
const OUT = join(ROOT, 'src/lib/tools/content.generated.ts')

export function renderIndex(slugs) {
  const lines = [
    '// GENERATED by scripts/gen-tools.mjs from src/content/tools/*.json — do not edit by hand.',
    '// Validated at module load by src/lib/tools/content.ts (src/lib/tools/spec.ts).',
    '',
  ]
  slugs.forEach((s, i) => lines.push(`import t${i} from '@/content/tools/${s}.json'`))
  if (slugs.length) lines.push('')
  lines.push('export const TOOL_CONTENT: Readonly<Record<string, unknown>> = {')
  slugs.forEach((s, i) => lines.push(`  '${s}': t${i},`))
  lines.push('}', '')
  return lines.join('\n')
}

export function contentSlugs(dir = DIR) {
  return existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort() : []
}

// Compared as real paths: through a symlink the two differ, and the script would exit 0 having written nothing (as carry-tools.mjs does).
if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  writeFileSync(OUT, renderIndex(contentSlugs()))
}
