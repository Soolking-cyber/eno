/**
 * Freezes this month's edition of the HCMC Teacher Cost & Pay Index (src/lib/teacher-cost-index.ts) from the live Rent
 * Index CSV. GET only: it reads https://eno.vn/hcmc-rent-index.csv once and writes two files in this checkout —
 * src/content/teacher-cost-index/<YYYY-MM>.json and the generated editions.ts beside it. No database, no deploy.
 *
 *   npx tsx scripts/teacher-cost-index-freeze.ts --dry-run          # fetch, check and print the edition; write nothing
 *   npx tsx scripts/teacher-cost-index-freeze.ts --sources "<names>"   # freeze this month's edition
 *   npx tsx scripts/teacher-cost-index-freeze.ts --sources "<names>" --series-break "<what changed, one sentence for readers>"
 *   npx tsx scripts/teacher-cost-index-freeze.ts --sources "<names>" --note "<what a reader of this edition must know>"
 *   npx tsx scripts/teacher-cost-index-freeze.ts --sources "<names>" --save-csv <path>  # also keep the exact bytes it froze (never overwrites)
 *   npx tsx scripts/teacher-cost-index-freeze.ts --fixture <csv> --now <iso> --dir <dir> --sources "<names>"   # rehearsals and tests (never the real tree)
 *   npx tsx scripts/teacher-cost-index-freeze.ts --reindex          # rebuild editions.ts from the directory, nothing else
 *
 * THE MONTHLY RUN, on the 1st in Ho Chi Minh City: freeze → vitest (the teacher-cost-index, pages sitemap and llms.txt
 * tests) → the gated commit → the owner deploys → GET-check the page, an edition, the CSV and the sitemap.
 * ⛔ `--sources` IS REQUIRED TO WRITE AN EDITION: the names after "Sources in this snapshot:" in the Rent Index's method
 * (https://eno.vn/hcmc-rent-index), copied as printed — its CSV does not carry them, and an edition must say what its rents
 * are (d1-spec §2.1). planEdition takes nothing but the Rent Index's own source labels: no count per source (owner, 2026-09-27).
 * ⛔ AN EDITION IS NEVER REWRITTEN. planEdition refuses an id already frozen, and the file is opened with `wx`, so a
 * second run cannot clobber it either; a correction is an erratum (src/content/teacher-cost-index/errata.json).
 * ⛔ A GUARD THAT STOPS THE FREEZE IS A SERIES BREAK, NOT A BUG (planEdition, seriesBreaks): read what changed on the
 * Rent Index (its method's dated lines) or in the model, then re-run with --series-break and the reason readers see.
 * ⚠️ `--now` ONLY WITH `--fixture`: a live freeze is dated by the clock, never by an argument.
 * ⛔ AN UNKNOWN OR MISTYPED FLAG IS A REFUSAL (`parseArgs`), never ignored: `--dryrun` for `--dry-run` would otherwise
 * run the real, unrepeatable freeze (codex, gate review).
 * ⚠️ THE ORDER OF WRITES: the saved CSV copy first (`wx`; checked before the fetch too), then the edition file — the commit
 * point — then the index, replaced atomically (a temp file renamed over it). If the index write fails, `--reindex` finishes
 * the job; the tests (the index matches the directory) refuse a commit until it has.
 * ⛔ `--fixture` WRITES ONLY WITH `--dir` (a rehearsal directory, never a real editions folder) OR NOT AT ALL (`--dry-run`):
 * a fixture's edition would name the live file as its source.
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, realpathSync, renameSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import {
  FreezeRefused, RENT_INDEX_CSV_URL, cellFigures, editionMonth, editionSchema, planEdition, saigonDay, shareText,
  type Edition,
} from '../src/lib/teacher-cost-index'

export const CONTENT_DIR = join(process.cwd(), 'src/content/teacher-cost-index')
const EDITION_FILE = /^(\d{4}-\d{2})\.json$/

/** Every frozen edition in `dir`, parsed (a malformed one stops the freeze here rather than at the build). */
export function readEditions(dir: string): Edition[] {
  return readdirSync(dir)
    .filter((f) => EDITION_FILE.test(f))
    .map((f) => editionSchema.parse(JSON.parse(readFileSync(join(dir, f), 'utf8'))))
}

/** The generated import list (src/content/teacher-cost-index/editions.ts), newest first. Static imports: always bundled. */
export function renderEditionsIndex(ids: readonly string[]): string {
  const sorted = [...ids].sort().reverse()
  const name = (id: string) => `e${id.replace('-', '_')}`
  return [
    '// GENERATED by scripts/teacher-cost-index-freeze.ts from src/content/teacher-cost-index/<YYYY-MM>.json — do not edit by hand.',
    '// Newest first. Parsed at module load by src/lib/teacher-cost-index-editions.ts, so a malformed edition fails the build.',
    '',
    ...sorted.map((id) => `import ${name(id)} from '@/content/teacher-cost-index/${id}.json'`),
    ...(sorted.length ? [''] : []),
    `export const EDITION_FILES: readonly unknown[] = [${sorted.map(name).join(', ')}]`,
    '',
  ].join('\n')
}

/** Rebuilds editions.ts from the edition files in `dir` — written to a temp file and renamed over it, never half-written. */
export function writeIndex(dir: string): string[] {
  const ids = readdirSync(dir).flatMap((f) => EDITION_FILE.exec(f)?.[1] ?? [])
  const tmp = join(dir, `.editions.ts.${process.pid}.tmp`)
  writeFileSync(tmp, renderEditionsIndex(ids))
  renameSync(tmp, join(dir, 'editions.ts'))
  return ids
}

/** Writes the edition — `wx`: never over an existing file — then the index of what is in `dir`. */
export function writeEdition(dir: string, edition: Edition): string {
  const file = join(dir, `${edition.edition}.json`)
  writeFileSync(file, `${JSON.stringify(edition, null, 2)}\n`, { flag: 'wx' })
  writeIndex(dir)
  return file
}

/** Any checkout's editions folder — what a fixture must never be frozen into. */
const REAL_EDITIONS = /[\\/]src[\\/]content[\\/]teacher-cost-index[\\/]?$/
/** The folder a path names once links are followed (macOS's /tmp is /private/tmp); a path not there yet, as written. */
const realDir = (p: string) => {
  try {
    return realpathSync(p)
  } catch {
    return resolve(p)
  }
}

const VALUE_FLAGS = ['--fixture', '--now', '--dir', '--save-csv', '--series-break', '--note', '--sources'] as const
const BARE_FLAGS = ['--dry-run', '--reindex'] as const
export type FreezeArgs = Partial<Record<(typeof VALUE_FLAGS)[number], string>> & Partial<Record<(typeof BARE_FLAGS)[number], true>>

/** The command line, or a refusal: an unknown flag, a stray word, a flag twice, a value missing, `--now` on a live run, a write without `--sources`. */
export function parseArgs(argv: readonly string[]): FreezeArgs {
  const out: Record<string, string | true> = {}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (Object.hasOwn(out, a)) throw new FreezeRefused(`${a} is given twice`)
    if ((BARE_FLAGS as readonly string[]).includes(a)) out[a] = true
    else if ((VALUE_FLAGS as readonly string[]).includes(a)) {
      const v = argv[i + 1]
      if (v === undefined || v.startsWith('--') || !v.trim()) throw new FreezeRefused(`${a} needs a value`)
      out[a] = v
      i++
    } else throw new FreezeRefused(`unknown argument ${JSON.stringify(a)} — the flags are ${[...VALUE_FLAGS, ...BARE_FLAGS].join(' ')}`)
  }
  if (out['--now'] && !out['--fixture']) throw new FreezeRefused('--now is for --fixture runs only: a live freeze is dated by the clock')
  // ⛔ A FIXTURE NEVER FREEZES INTO THE REAL EDITIONS: its edition would claim the live file as its source, dated by --now,
  // and pass every check (opus, gate review). So it writes only into a rehearsal directory, or not at all.
  if (out['--fixture'] && !out['--dir'] && !out['--dry-run']) throw new FreezeRefused('--fixture writes only with --dir <a rehearsal directory>, or with --dry-run')
  // ⛔ …AND A REHEARSAL DIRECTORY IS NEVER A REAL EDITIONS FOLDER, this checkout's or another's, however it is spelled or
  // linked: `--dir src/content/teacher-cost-index` would freeze the fixture for real (codex, gate review).
  if (out['--fixture'] && typeof out['--dir'] === 'string' && REAL_EDITIONS.test(realDir(out['--dir']))) {
    throw new FreezeRefused(`--fixture never writes into the real editions (${out['--dir']}): give --dir a rehearsal directory`)
  }
  if (out['--reindex'] && Object.keys(out).some((k) => k !== '--reindex' && k !== '--dir')) throw new FreezeRefused('--reindex takes only --dir')
  // ⛔ AN EDITION SAYS WHAT ITS RENTS ARE: nothing is written without the snapshot's sources (a dry run may leave them out).
  if (!out['--reindex'] && !out['--dry-run'] && !out['--sources']) {
    throw new FreezeRefused('--sources is required to write an edition: the names after "Sources in this snapshot:" on https://eno.vn/hcmc-rent-index ("How the index is calculated"), as printed')
  }
  return out as FreezeArgs
}

export const sha256 = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex')

/**
 * One GET. A non-200 is refused with the body's first words (a 503 says why); nothing is retried behind your back, and a
 * stalled origin is a refusal after a minute, never a hung freeze (opus, gate review).
 */
async function fetchCsv(): Promise<Buffer> {
  let res: Response
  let body: Buffer
  try {
    res = await fetch(RENT_INDEX_CSV_URL, { headers: { accept: 'text/csv' }, redirect: 'error', signal: AbortSignal.timeout(60_000) })
    body = Buffer.from(await res.arrayBuffer())
  } catch (e) {
    throw new FreezeRefused(`GET ${RENT_INDEX_CSV_URL} failed: ${e instanceof Error ? e.message : String(e)}`)
  }
  if (res.status !== 200) throw new FreezeRefused(`GET ${RENT_INDEX_CSV_URL} answered ${res.status}: ${body.toString('utf8').slice(0, 160).trim()}`)
  return body
}

function summary(e: Edition): string {
  const line = (label: string, slug: string, scope: 'city' | 'district', band: Parameters<typeof cellFigures>[3]) => {
    const cell = e.rent.cells.find((c) => c.scope === scope && c.districtSlug === slug && c.band === band)!
    const f = cellFigures(e, scope, slug, band)
    return `  ${label.padEnd(10)} ${f ? `${f.cell.medianVnd.toLocaleString('en-US')} đ (n=${cell.n}) → ${shareText(f.shareWhole)}` : `— (n=${cell.n})`}`
  }
  return [
    `edition ${e.edition} (${editionMonth(e.edition)}), frozen ${e.frozenAt}`,
    `rent snapshot ${e.rent.snapshotUtc} (${saigonDay(e.rent.snapshotUtc)} in Saigon), rules v${e.rent.rulesVersion}, csv sha256 ${e.rent.csvSha256}`,
    `take-home ${e.model.takeHome.map((t) => `${t.grossVnd.toLocaleString('en-US')} → ${t.takeHomeVnd.toLocaleString('en-US')}`).join(' · ')} (model v${e.model.version})`,
    line('studio', 'all', 'city', 'studio'),
    line('1 bedroom', 'all', 'city', 'br1'),
    line('2 bedrooms', 'all', 'city', 'br2'),
    line('3+', 'all', 'city', 'br3plus'),
    `${new Set(e.rent.cells.filter((c) => c.scope === 'district').map((c) => c.districtSlug)).size} districts · ${e.outputs.length / e.model.takeHome.length} published cells`,
    `sources: ${e.rent.sources ?? '— (none given: writing an edition needs --sources)'}`,
    ...(e.seriesBreak ? [`series break: ${e.seriesBreak}`] : []),
    ...(e.note ? [`note: ${e.note}`] : []),
  ].join('\n')
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  const dir = args['--dir'] ?? CONTENT_DIR
  if (args['--reindex']) {
    console.log(`editions.ts lists ${writeIndex(dir).sort().reverse().join(', ') || 'no edition'}`)
    return
  }
  const now = args['--now'] ? new Date(args['--now']) : new Date()
  if (!Number.isFinite(now.getTime())) throw new FreezeRefused(`--now ${args['--now']} is not a time`)
  const saveCsv = args['--save-csv']
  // Before anything is fetched or written: the record copy must not land on an existing file (`wx` below, too), and its
  // directory must be there — found missing only at the write, it was a raw ENOENT after the fetch (verifier round).
  if (saveCsv && existsSync(saveCsv)) throw new FreezeRefused(`--save-csv ${saveCsv} already exists`)
  if (saveCsv && !statSync(dirname(resolve(saveCsv)), { throwIfNoEntry: false })?.isDirectory()) {
    throw new FreezeRefused(`--save-csv ${saveCsv}: its directory ${dirname(resolve(saveCsv))} does not exist — create it (mkdir -p), then re-run`)
  }

  const bytes = args['--fixture'] ? readFileSync(args['--fixture']) : await fetchCsv()
  const edition = planEdition({
    csvText: bytes.toString('utf8'),
    csvSha256: sha256(bytes),
    now,
    editions: readEditions(dir),
    seriesBreak: args['--series-break'],
    note: args['--note'],
    sources: args['--sources'],
  })
  console.log(summary(edition))
  if (args['--dry-run']) {
    console.log('dry run: nothing written')
    return
  }
  // The record copy first: if it cannot be written, nothing is frozen yet and a re-run can fetch again; written after the
  // edition, a failure would lose the very bytes the edition was frozen from (codex, gate review).
  if (saveCsv) {
    writeFileSync(saveCsv, bytes, { flag: 'wx' })
    console.log(`saved the frozen CSV: ${saveCsv}`)
  }
  console.log(`wrote ${writeEdition(dir, edition)} and editions.ts`)
}

if (process.argv[1]?.endsWith('teacher-cost-index-freeze.ts')) {
  main().catch((e) => {
    console.error(e instanceof FreezeRefused ? `REFUSED: ${e.message}` : e)
    process.exit(1)
  })
}
