#!/usr/bin/env node
/**
 * Regenerates src/lib/guides/content.generated.ts from src/content/guides/*.json. A JSON file read with `fs` at run time would not reach the standalone build, so each is imported.
 * guides.test.ts fails while this file is out of step with the directory. Usage: node scripts/gen-guides.mjs
 */
import { readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(fileURLToPath(import.meta.url), '..', '..')
const DIR = join(ROOT, 'src/content/guides')
const OUT = join(ROOT, 'src/lib/guides/content.generated.ts')

export function renderIndex(slugs) {
  const lines = [
    '// GENERATED by scripts/gen-guides.mjs from src/content/guides/*.json — do not edit by hand.',
    '// Validated at module load by src/lib/guides/content.ts (src/lib/teach-guides/schema.ts).',
    '',
  ]
  slugs.forEach((s, i) => lines.push(`import g${i} from '@/content/guides/${s}.json'`))
  if (slugs.length) lines.push('')
  lines.push('export const GUIDE_CONTENT: Readonly<Record<string, unknown>> = {')
  slugs.forEach((s, i) => lines.push(`  '${s}': g${i},`))
  lines.push('}', '')
  return lines.join('\n')
}

export function contentSlugs() {
  return readdirSync(DIR).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort()
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, renderIndex(contentSlugs()))
}
