#!/usr/bin/env node
/**
 * Regenerates src/lib/teach-guides/content.generated.ts from src/content/teach-in-vietnam/*.json.
 *
 * Static imports, not fs reads: the route renders most guides for the first time at RUNTIME (they are
 * released in waves — src/lib/teach-guides/registry.ts), and a JSON file read with `fs` is only in the
 * standalone server image if output tracing happens to find it. An import is bundled, always.
 * teach-guides.test.ts fails while this file is out of step with the directory.
 *
 *   node scripts/gen-teach-guides.mjs
 */
import { readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(fileURLToPath(import.meta.url), '..', '..')
const DIR = join(ROOT, 'src/content/teach-in-vietnam')
const OUT = join(ROOT, 'src/lib/teach-guides/content.generated.ts')

export function renderIndex(slugs) {
  const lines = [
    '// GENERATED by scripts/gen-teach-guides.mjs from src/content/teach-in-vietnam/*.json — do not edit by hand.',
    '// Validated at module load by src/lib/teach-guides/content.ts (schema.ts).',
    '',
  ]
  slugs.forEach((s, i) => lines.push(`import g${i} from '@/content/teach-in-vietnam/${s}.json'`))
  lines.push('', 'export const TEACH_CONTENT: Readonly<Record<string, unknown>> = {')
  slugs.forEach((s, i) => lines.push(`  '${s}': g${i},`))
  lines.push('}', '')
  return lines.join('\n')
}

export function contentSlugs() {
  return readdirSync(DIR)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -5))
    .sort()
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const slugs = contentSlugs()
  writeFileSync(OUT, renderIndex(slugs))
  console.log(`teach-guides: ${slugs.length} guides → ${OUT.slice(ROOT.length + 1)}`)
}
