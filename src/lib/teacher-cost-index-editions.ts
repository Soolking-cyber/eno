import { EDITION_FILES } from '@/content/teacher-cost-index/editions'
import ERRATA_FILE from '@/content/teacher-cost-index/errata.json'
import { editionSchema, erratumSchema, newestFirst, type Edition, type Erratum } from '@/lib/teacher-cost-index'

/**
 * The frozen editions of the HCMC Teacher Cost & Pay Index, newest first, and their errata — the only data the page,
 * the CSV, the sitemap and the teach hub's line read (src/lib/teacher-cost-index.ts says why nothing reads the database).
 *
 * ⚠️ PARSED AT MODULE LOAD, so a malformed edition or erratum fails `next build` — the teach guides' rule (content.ts):
 * a broken data page should be loud in CI, never half-rendered in front of a crawler.
 * ⚠️ STATIC IMPORTS (editions.ts, generated by the freeze script), never an fs read: an import is always in the
 * standalone image; a file read is only there if output tracing happens to find it.
 */
export const EDITIONS: readonly Edition[] = EDITION_FILES.map((f) => editionSchema.parse(f)).sort(newestFirst)

/** Append-only corrections, each printed beside its edition and in its CSV `note`. */
export const ERRATA: readonly Erratum[] = erratumSchema.array().parse(ERRATA_FILE)

export const editionById = (id: string): Edition | undefined => EDITIONS.find((e) => e.edition === id)
