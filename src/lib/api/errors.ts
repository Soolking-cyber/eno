/**
 * THE ERROR VOCABULARY THAT IS ALREADY ON THE WIRE.
 *
 * ⚠️ THIS FILE ADDS A TYPE, NOT A BEHAVIOUR. Every member below was harvested from the 669
 * `NextResponse.json({ error: '…' })` returns across the 167 first-party route handlers on
 * 2026-08-06. Nothing is renamed, nothing is dropped, and no response changes by a single byte.
 * That is deliberate and it is the whole migration strategy: clients branch on these strings today
 *   src/app/messages/[id]/page.tsx      data?.error === 'human_help_pending'
 *   src/app/disputes/[id]/page.tsx      uj?.error === 'already_submitted'
 *   src/app/onboard/onboard-client.tsx  data?.error === 'phone_taken'
 *   src/components/marketplace/bulk-upload-panel.tsx  d.error === 'business_only'
 * so a rename is invisible to the compiler and breaks the UI silently. Adopting the existing
 * strings first means the type can go in with zero risk, and the tidying becomes a separate,
 * reviewable step where each rename moves the server AND its call site together.
 *
 * ⚠️ THE COLLISIONS ARE PRESERVED ON PURPOSE — they are the best argument for the type.
 *   'forbidden'    (21 sites)  vs  'Forbidden'    (16 sites)
 *   'unauthorized' ( 1 site )  vs  'Unauthorized' ( 1 site )
 * A client testing `err === 'forbidden'` is right slightly more than half the time. Both spellings
 * are listed because both are live; deleting one from the type would not delete it from the wire,
 * it would just stop TypeScript describing reality. Collapsing them is step 5 of the plan, one code
 * per commit, server and client together.
 *
 * ⚠️ THE LONG TAIL IS 165 SINGLE-USE CODES and that is a finding, not an accident of harvesting.
 * `invalid_body`, `invalid_request`, `bad_request`, `missing_fields` and twenty-six other
 * `invalid_*` variants all mean "your input was wrong". Nothing forced a choice between them, so
 * every author picked one. Listing them together is the first time that has been visible in one
 * place; consolidating is future work, and the type is what will make it safe.
 *
 * Generated by harvesting the routes, then hand-grouped. Regenerate with:
 *   git ls-files 'src/app/api/**\/route.ts' 'src/app/api/**\/route.svc.ts' | grep -v '/api/v1/' \
 *     | xargs grep -hoE "(error: '|ApiError\('|apiFail\(')[A-Za-z0-9_.-]+'" \
 *     | sed -E "s/.*'([A-Za-z0-9_.-]+)'/\1/" | sort | uniq -c
 * (three forms: the pre-wrapper `{ error: 'x' }`, and `ApiError('x')` / `apiFail('x')` from
 * `src/lib/api/handler.ts` — a migrated route emits the same string through a different shape.)
 */

