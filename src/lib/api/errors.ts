/** Every error code this API can return today. */
export type ApiErrorCode = SharedApiErrorCode | NicheApiErrorCode

/**
 * The shape every first-party handler returns on failure. Matches what the routes emit today —
 * a bare `{ error }` — rather than the richer `{ error: { code, message } }` envelope `/api/v1`
 * uses, because changing the shape is a wire change and this file is explicitly not that.
 */
export type ApiErrorBody = { error: ApiErrorCode }

/**
 * Narrow an unknown JSON body to a known error code. Use on the CLIENT, where the alternative is
 * `data?.error === 'some_string'` with no compiler involvement at all.
 *
 * Returns `null` for a body that is not a recognised error — including a code that exists on the
 * server but is missing from this file, which is the case worth thinking about: it means the
 * harvest is stale. Prefer regenerating (see the header) over adding one member by hand.
 */
export function apiErrorCode(body: unknown): ApiErrorCode | null {
  if (!body || typeof body !== 'object') return null
  const e = (body as { error?: unknown }).error
  return typeof e === 'string' && (ALL as readonly string[]).includes(e) ? (e as ApiErrorCode) : null
}

