/**
 * ⚠️ `satisfies` IS ONE-DIRECTIONAL, WHICH IS NOT ENOUGH. It proves every entry of `ALL` is a member
 * of the union; it does NOT prove every member of the union appears in `ALL`. A code added to the
 * type but not the array would compile cleanly and then make `apiErrorCode()` return `null` for a
 * perfectly real error at runtime — the exact silent failure this file exists to remove. Pointed out
 * in review.
 *
 * This line closes the other direction: if any union member is missing from `ALL`, `Missing` is not
 * `never` and the assignment fails to compile, naming the absent codes in the error.
 */
type Missing = Exclude<ApiErrorCode, (typeof ALL)[number]>
