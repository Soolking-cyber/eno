function DrawerContent({
  className,
  children,
  ...props
}: DrawerPrimitive.Popup.Props) {
  const { hasSnapPoints, modal, showSwipeHandle, swipeDirection } = useDrawer()
  const swipeAxis =
    swipeDirection === "down" || swipeDirection === "up" ? "y" : "x"
  // KEYBOARD-AWARE GEOMETRY (mobile web + the Capacitor shell) — see the same block in
  // ui/dialog.tsx. A bottom sheet pinned to the LAYOUT viewport's bottom sits UNDER the
  // on-screen keyboard on iOS (which overlays rather than resizes), so its footer action
  // is unreachable the moment a field inside it takes focus. The lift is the app-wide
  // contract var `--kb-h` (globals.css, "KEYBOARD-AWARE SURFACES"): the distance a
  // `bottom: 0` element must rise, ALREADY net of WebKit's own pan, 0px while closed.
  // ⚠️ This file used to rebuild that number locally as `100dvh - --vvt - --vvh` (a local
  // `--kb-inset`) — identical to --kb-h on the web, but natively --vvt is pinned to 0, so
  // the local copy was the RAW keyboard height and the sheet rose by WebKit's pan on top of
  // it (double lift → a gap between the sheet and the keyboard). Consume --kb-h, don't
  // re-derive it. This is the `.kb-lift` idea applied through the drawer's OWN --translate-y
  // (the popup is already transformed for swipe/stacking, so no new containing block is
  // created and the lift rides the existing 450ms transform transition instead of reflowing).
  // The React boolean stays as the coarse on/off switch for the footer's safe-area swap and
  // the height clamp; per-frame geometry stays in CSS, because a per-frame render aborts the
  // iOS keyboard.
  const { open: keyboardOpen } = useVirtualKeyboard()

  return (
    <DrawerPortal data-slot="drawer-portal">
      {modal === true && (
        <DrawerOverlay data-snap-points={hasSnapPoints ? "" : undefined} />
      )}
      <DrawerPrimitive.Viewport
        data-slot="drawer-viewport"
        data-modal={modal}
        className="pointer-events-none fixed inset-0 z-50 select-none data-[modal=true]:pointer-events-auto"
      >
        <DrawerPrimitive.Popup
          data-slot="drawer-popup"
          data-swipe-axis={swipeAxis}
          data-snap-points={hasSnapPoints ? "" : undefined}
          data-kb-open={keyboardOpen ? "" : undefined}
          className={cn(
            // Base.
            "group/drawer-popup pointer-events-auto fixed z-50 m-(--drawer-inset,0px) flex h-(--drawer-content-height) max-h-(--drawer-content-max-height,none) min-h-0 w-(--drawer-content-width,auto) transform-[translate3d(var(--translate-x,0px),var(--translate-y,0px),0)_scale(var(--stack-scale))] flex-col bg-popover text-sm text-popover-foreground transition-[transform,height,opacity,filter] duration-450 ease-[cubic-bezier(0.22,1,0.36,1)] will-change-transform outline-none select-none [interpolate-size:allow-keywords] data-[swipe-direction=down]:rounded-t-2xl data-[swipe-direction=down]:border-t data-[swipe-direction=left]:rounded-r-2xl data-[swipe-direction=left]:border-r data-[swipe-direction=right]:rounded-l-2xl data-[swipe-direction=right]:border-l data-[swipe-direction=up]:rounded-b-2xl data-[swipe-direction=up]:border-b",
            // Nested.
            "data-nested-drawer-open:overflow-hidden data-nested-drawer-open:brightness-95",
            // Bleed.
            "after:pointer-events-none after:absolute after:bg-(--drawer-bleed-background,var(--color-popover)) data-[swipe-axis=x]:after:inset-y-0 data-[swipe-axis=x]:after:w-(--bleed) data-[swipe-axis=y]:after:inset-x-0 data-[swipe-axis=y]:after:h-(--bleed) data-[swipe-direction=down]:after:top-full data-[swipe-direction=left]:after:right-full data-[swipe-direction=right]:after:left-full data-[swipe-direction=up]:after:bottom-full",
            // Sizing. Resting value unchanged (100dvh-6rem).
            "[--drawer-content-height:var(--drawer-height,auto)] data-[swipe-axis=x]:[--drawer-content-width:75%] data-[swipe-axis=y]:[--drawer-content-max-height:calc(100dvh-6rem)] data-[swipe-axis=y]:data-snap-points:[--drawer-content-height:100dvh] data-[swipe-axis=x]:sm:[--drawer-content-width:24rem]",
            // Sizing while the keyboard is up: whichever is SMALLER — the resting cap, or what
            // is still VISIBLE (--vvh, published for both platforms) less 2rem of clearance.
            // The sheet's bottom edge is lifted flush onto the keyboard top, so this is what
            // stops a tall sheet from running off the top of the visible strip. Two attributes
            // ⇒ higher specificity than the resting rule above, so it wins while kb-open and
            // is completely absent (no --vvh dependency at all) otherwise.
            "data-[swipe-axis=y]:data-kb-open:[--drawer-content-max-height:min(calc(100dvh-6rem),calc(var(--vvh,100dvh)-2rem))]",
            // Stack.
            "[--bleed:3rem] [--peek:1rem] [--stack-height:var(--drawer-frontmost-height,var(--drawer-height,0px))] [--stack-peek-offset:max(0px,calc((var(--nested-drawers)-var(--stack-progress))*var(--peek)))] [--stack-progress:clamp(0,var(--drawer-swipe-progress),1)] [--stack-scale-base:max(0,calc(1-(var(--nested-drawers)*var(--stack-step))))] [--stack-scale:clamp(0,calc(var(--stack-scale-base)+(var(--stack-step)*var(--stack-progress))),1)] [--stack-shrink:calc(1-var(--stack-scale))] [--stack-step:0.05]",
            // Transitions.
            // ⚠️ THESE DURATIONS ARE DELIBERATELY LEFT ON THE CSS DEFAULT (`ease`) — do not
            // "pair" them with a token the way the rest of the sweep did.
            // They are gesture physics, not decoration: the close duration is computed from how
            // hard the user flicked (--drawer-swipe-strength), and `duration-0` is what lets the
            // sheet track a finger 1:1 while swiping. A spring here would overshoot past the
            // dock edge (see the boundary rule in globals.css), and any curve at all would make
            // the sheet lag or lead the finger instead of following it. The motion sweep of
            // 2026-08-21 skipped this line for exactly that reason.
            "data-ending-style:transform-(--closed-transform) data-ending-style:opacity-[0.9999] data-ending-style:duration-[calc(var(--drawer-swipe-strength)*400ms)] data-nested-drawer-swiping:duration-0 data-ending-style:data-nested-drawer-swiping:duration-[calc(var(--drawer-swipe-strength)*400ms)] data-starting-style:transform-(--closed-transform) data-swiping:duration-0 data-ending-style:data-swiping:duration-[calc(var(--drawer-swipe-strength)*400ms)]",
            // Axis: y.
            "data-[swipe-axis=y]:inset-x-0 data-[swipe-axis=y]:data-nested-drawer-open:h-(--stack-height)",
            // Axis: x.
            "data-[swipe-axis=x]:inset-y-0 data-[swipe-axis=x]:flex-row",
            // Direction: down. The trailing `-var(--kb-h,0px)` is the keyboard lift: it rides
            // the popup's existing transform transition (GPU, no reflow) and is 0px otherwise.
            // With every other term at rest the sheet's bottom edge then SETTLES exactly on the
            // keyboard top on both platforms. Read live (not gated on the React boolean) because
            // the var already self-zeroes and following it re-settles the sheet flush after
            // WebKit pans — the 450ms transform transition means it chases, never leads.
            "data-[swipe-direction=down]:bottom-0 data-[swipe-direction=down]:origin-bottom data-[swipe-direction=down]:[--closed-transform:translate3d(0,calc(100%+var(--drawer-inset,0px)+2px),0)] data-[swipe-direction=down]:[--translate-y:calc(var(--drawer-snap-point-offset,0px)+var(--drawer-swipe-movement-y)-var(--stack-peek-offset)-(var(--stack-shrink)*var(--stack-height))-var(--kb-h,0px))]",
            // Direction: up.
            "data-[swipe-direction=up]:top-0 data-[swipe-direction=up]:origin-top data-[swipe-direction=up]:[--closed-transform:translate3d(0,calc(-100%-var(--drawer-inset,0px)-2px),0)] data-[swipe-direction=up]:[--translate-y:calc(var(--drawer-snap-point-offset,0px)+var(--drawer-swipe-movement-y)+var(--stack-peek-offset)+(var(--stack-shrink)*var(--stack-height)))]",
            // Direction: left.
            "data-[swipe-direction=left]:left-0 data-[swipe-direction=left]:origin-left data-[swipe-direction=left]:[--closed-transform:translate3d(calc(-100%-var(--drawer-inset,0px)-2px),0,0)] data-[swipe-direction=left]:[--translate-x:calc(var(--drawer-swipe-movement-x)+var(--stack-peek-offset)+(var(--stack-shrink)*100%))]",
            // Direction: right.
            "data-[swipe-direction=right]:right-0 data-[swipe-direction=right]:origin-right data-[swipe-direction=right]:[--closed-transform:translate3d(calc(100%+var(--drawer-inset,0px)+2px),0,0)] data-[swipe-direction=right]:[--translate-x:calc(var(--drawer-swipe-movement-x)-var(--stack-peek-offset)-(var(--stack-shrink)*100%))]",
            className
          )}
          {...props}
        >
          {showSwipeHandle && <DrawerSwipeHandle />}
          <DrawerPrimitive.Content
            data-slot="drawer-content"
            className={cn(
              "flex min-h-0 flex-1 flex-col overflow-hidden overscroll-contain rounded-[inherit] transition-opacity duration-300 ease-[cubic-bezier(0.45,1.005,0,1.005)] select-text group-data-nested-drawer-open/drawer-popup:opacity-0 group-data-nested-drawer-swiping/drawer-popup:opacity-100 group-data-swiping/drawer-popup:select-none"
            )}
          >
            {children}
          </DrawerPrimitive.Content>
        </DrawerPrimitive.Popup>
      </DrawerPrimitive.Viewport>
    </DrawerPortal>
  )
}

